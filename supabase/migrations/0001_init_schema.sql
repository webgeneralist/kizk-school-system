-- updated_at を自動更新する共通トリガー関数
create or replace function set_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

-- ----------------------------------------------------------------------------
-- academies（学院＝テナント）
-- ----------------------------------------------------------------------------
create table academies (
  id              integer generated by default as identity primary key,
  code            varchar(50) not null unique,
  name            varchar(200) not null,
  address         varchar(300),
  phone           varchar(20),
  principal_name  varchar(100),
  contact_email   varchar(200),
  is_active       boolean not null default true,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create trigger trg_academies_updated_at before update on academies
  for each row execute function set_updated_at();

-- ----------------------------------------------------------------------------
-- admin_users（スタッフ・管理者プロフィール。認証自体はSupabase Authが担う）
-- ----------------------------------------------------------------------------
create table admin_users (
  id             integer generated by default as identity primary key,
  auth_user_id   uuid unique references auth.users(id) on delete set null,
  academy_id     integer references academies(id),
  username       varchar(50) not null unique,
  display_name   varchar(100) not null,
  role           varchar(10) not null default 'staff' check (role in ('super','staff')),
  is_kizk_admin  boolean not null default false,
  is_active      boolean not null default true,
  last_login     timestamptz,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create trigger trg_admin_users_updated_at before update on admin_users
  for each row execute function set_updated_at();

-- ----------------------------------------------------------------------------
