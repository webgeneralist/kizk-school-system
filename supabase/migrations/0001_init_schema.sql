-- ============================================================================
-- Row Level Security
-- ============================================================================
-- 現段階（Phase 1 MVP）では「ログイン済みユーザーのみアクセス可」までを担保する。
-- 学院ごとのデータ分離（academy_idでのスコープ）はPhase 4で admin_users.academy_id と
-- auth.uid() を突き合わせるポリシーに強化すること。それまでは匿名アクセスの遮断のみ。

do $$
declare
  t text;
begin
  for t in
    select unnest(array[
      'academies','admin_users','schools','students','attendance','calendar_events',
      'worksheet_files','assignments','assignment_scores','student_subject_levels',
      'weak_points','learning_progress','hs_reports','report_sends',
      'messages','message_reads','message_replies','todo_items','todo_checks',
      'sns_goals','sns_goal_posts','operation_logs','system_settings'
    ])
  loop
    execute format('alter table %I enable row level security', t);
    execute format(
      'create policy %I on %I for all to authenticated using (true) with check (true)',
      t || '_authenticated_all', t
    );
  end loop;
end $$;
